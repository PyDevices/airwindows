"""Writes what binds the generated kernels to each interpreter:

  src/airwindows/registry.h, registry.c  every plug-in a build carries
  src/airwindows/selection.txt           names, collections and the board
                                         default, for micropython.mk/.cmake
  src/audioairwindows/module.c           the MicroPython module table
  src/audioairwindows/types.c            a MicroPython type per plug-in
  src/cpython/audioairwindows.py         a CPython class per plug-in
  audioairwindows.pyi                    the stub, for both
  docs/reference/plugins.md              the list, by category

Every plug-in's code is guarded by AW_WITH_ALL or AW_WITH_<Name>, so one
set of files serves a desktop build with everything and a board build with
the few it chose.
"""

import re
from pathlib import Path

GUARD = "#if AW_WITH_ALL || defined(AW_WITH_{n})"
HEAD_C = """\
// GENERATED by tools/awgen. Do not edit: change the generator and run
// `python -m tools.awgen`.
//
// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: Copyright (c) 2026 Brad Barnett
"""

# Plug-ins every board build carries whatever the collections say: the ones
# this module shipped with before it carried everything.
ALWAYS = ("Galactic", "PurestDrive", "ButterComp2")
MAX_PARAMS = 64


def board_default(index, policy):
    names = {n for n, v in index.items()
             if {"Basic", "Recommended"} & set(v["collections"])}
    names |= set(ALWAYS)
    return sorted(n for n in names if n in index and
                  policy.get(n, {}).get("board", True))


def registry(names):
    h = HEAD_C + """
// Every plug-in this build compiled, by name. A desktop build has them all.

#pragma once

#include "airwindows/plugin.h"

#ifdef __cplusplus
extern "C" {
#endif

// NULL-terminated.
extern const aw_plugin_t *const aw_plugins[];

#ifdef __cplusplus
}
#endif
"""
    c = [HEAD_C, '#include "airwindows/registry.h"', "",
         "#include <stddef.h>", ""]
    for n in names:
        c += [GUARD.format(n=n), "extern const aw_plugin_t aw_plugin_%s;" % n,
              "#endif"]
    c += ["", "const aw_plugin_t *const aw_plugins[] = {"]
    for n in names:
        c += [GUARD.format(n=n), "    &aw_plugin_%s," % n, "#endif"]
    c += ["    NULL,", "};", ""]
    return h, "\n".join(c)


def selection(index, default):
    lines = ["# GENERATED by tools/awgen. One plug-in per line: its name, then",
             "# the collections it is in, and `default` if a board build",
             "# carries it unless told otherwise."]
    for n in sorted(index):
        tags = list(index[n]["collections"])
        if n in default:
            tags.append("default")
        lines.append(" ".join([n] + tags))
    return "\n".join(lines) + "\n"


def mp_module(names):
    out = [HEAD_C.replace("//\n// SPDX", "//\n// audioairwindows' module "
                          "table: one type per plug-in this build carries.\n"
                          "//\n// SPDX", 1)]
    out.append("""\
#include "py/obj.h"
#include "py/objstr.h"

#include "airwindows/plugin.h"

// Declared here rather than by including Airwindows.h, and this file is listed
// first in micropython.mk: MicroPython 1.29's qstr scan fails when the first
// qstr of the first source sits in a header (audiocore/__init__.h has one).
""")
    for n in names:
        out += [GUARD.format(n=n),
                "extern const mp_obj_type_t audioairwindows_type_%s;" % n,
                "#endif"]
    out.append("""
#ifndef AW_VERSION
#define AW_VERSION "unknown"
#endif

// The commit this firmware was built from: -DAW_REVISION from
// micropython.mk, or the header micropython.cmake generates.
#ifdef AW_REVISION_HEADER
#include "audioairwindows_revision.h"
#endif
#ifndef AW_REVISION
#define AW_REVISION "unknown"
#endif

#ifndef AW_FAST_DEFAULT
#define AW_FAST_DEFAULT 0
#endif

static MP_DEFINE_STR_OBJ(audioairwindows_version_obj, AW_VERSION);
static MP_DEFINE_STR_OBJ(audioairwindows_revision_obj, AW_REVISION);

static const mp_rom_map_elem_t audioairwindows_module_globals_table[] = {
    { MP_ROM_QSTR(MP_QSTR___name__), MP_ROM_QSTR(MP_QSTR_audioairwindows) },
    { MP_ROM_QSTR(MP_QSTR___version__), MP_ROM_PTR(&audioairwindows_version_obj) },
    { MP_ROM_QSTR(MP_QSTR___revision__), MP_ROM_PTR(&audioairwindows_revision_obj) },
    // Whether this build runs the fast path (Airwindows.h, AW_FAST_DEFAULT).
    #if AW_FAST_DEFAULT
    { MP_ROM_QSTR(MP_QSTR_FAST), MP_ROM_TRUE },
    #else
    { MP_ROM_QSTR(MP_QSTR_FAST), MP_ROM_FALSE },
    #endif
    // Whether that fast path runs the S3's tuned kernels
    // (airwindows/plugin.h, AW_TUNED).
    #if AW_FAST_DEFAULT && AW_TUNED
    { MP_ROM_QSTR(MP_QSTR_TUNED), MP_ROM_TRUE },
    #else
    { MP_ROM_QSTR(MP_QSTR_TUNED), MP_ROM_FALSE },
    #endif""")
    for n in names:
        out += [GUARD.format(n=n),
                "    { MP_ROM_QSTR(MP_QSTR_%s), "
                "MP_ROM_PTR(&audioairwindows_type_%s) }," % (n, n),
                "#endif"]
    out.append("""};
static MP_DEFINE_CONST_DICT(audioairwindows_module_globals,
    audioairwindows_module_globals_table);

const mp_obj_module_t audioairwindows_module = {
    .base = { &mp_type_module },
    .globals = (mp_obj_dict_t *)&audioairwindows_module_globals,
};

MP_REGISTER_MODULE(MP_QSTR_audioairwindows, audioairwindows_module);
""")
    return "\n".join(out)


def mp_types(names):
    out = [HEAD_C, '#include "audioairwindows/Airwindows.h"', "",
           '#include "cp_compat/objproperty.h"', ""]
    for n in names:
        out += [GUARD.format(n=n),
                "extern const aw_plugin_t aw_plugin_%s;" % n,
                "MP_DEFINE_CONST_OBJ_TYPE(",
                "    audioairwindows_type_%s," % n,
                "    MP_QSTR_%s," % n,
                "    MP_TYPE_FLAG_HAS_SPECIAL_ACCESSORS,",
                "    make_new, audioairwindows_make_new,",
                "    attr, cp_compat_attr,",
                "    locals_dict, &audioairwindows_locals,",
                "    protocol, &audioairwindows_proto",
                "    );",
                "#endif"]
    out += ["", "const audioairwindows_entry_t audioairwindows_entries[] = {"]
    for n in names:
        out += [GUARD.format(n=n),
                "    {&audioairwindows_type_%s, &aw_plugin_%s}," % (n, n),
                "#endif"]
    out += ["    {NULL, NULL},", "};", "",
            "const size_t audioairwindows_entry_count =",
            "    sizeof(audioairwindows_entries) / "
            "sizeof(audioairwindows_entries[0]) - 1;", ""]
    return "\n".join(out)


def sentence(name, summary):
    """Upstream's one-liner reads "is a ..." after the name."""
    s = (summary or "").strip()
    if not s:
        return "Airwindows %s." % name
    if not s.endswith((".", "!", "?")):
        s += "."
    return "%s %s" % (name, s) if re.match(r"(is|are|does|has)\b", s) else s


def py_classes(index, names):
    out = ["", "# One class per plug-in, generated from upstream's list.", ""]
    for n in names:
        params = index[n]["params"]
        doc = sentence(n, index[n]["summary"])
        doc = doc.replace("\\", "\\\\").replace('"""', "'''")
        knobs = ", ".join(p["py"] for p in params) or "no parameters"
        out += ["", "class %s(_Airwindows):" % n,
                '    """%s' % doc, "", "    Parameters: %s." % knobs,
                '    """',
                "    _NAME = %r" % n,
                "    _PARAMS = (%s)" % "".join("%r, " % p["py"]
                                               for p in params).rstrip(" "),
                "    _NAMES = (%s)" % "".join("%r, " % p["name"]
                                              for p in params).rstrip(" "),
                "    _DEFAULTS = (%s)" % "".join(
                    "%r, " % round(float(p["default"]), 6)
                    for p in params).rstrip(" "),
                ""]
    out += ["", "__all__ = (%s)" % "".join("%r, " % n for n in names)
            .rstrip(" ")]
    return "\n".join(out) + "\n"


def pyi_classes(index, names):
    out = []
    for n in names:
        params = index[n]["params"]
        doc = sentence(n, index[n]["summary"]).replace('"""', "'''")
        args = "".join(",\n                 %s: float = %r" % (
            p["py"], round(float(p["default"]), 6)) for p in params)
        out += ["class %s(_Airwindows):" % n, '    """%s"""' % doc, "",
                "    def __init__(self, sample_rate: int = 48000, "
                "channel_count: int = 2%s) -> None: ..." % (
                    (", *" + args) if params else ""), ""]
    return "\n".join(out)


def _cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def plugins_md(index, names, default, policy, failed):
    fast_ref = sorted(n for n in names if policy.get(n, {}).get("fast")
                      is False)
    out = ["<!-- GENERATED by tools/awgen from upstream's plug-in list and "
           "tools/awgen/policy.json. Do not edit. -->", "",
           "# The plug-ins", "",
           "audioairwindows carries %d of Airwindows' %d plug-ins, each a "
           "class of the same name. A desktop install has every one; a board "
           "build has the %d marked **board** unless you choose others "
           "([Install](../get-started/install.md#choose-the-plug-ins)). They "
           "are grouped here by upstream's categories, and every parameter "
           "is the plug-in's own 0 to 1 knob, as its keyword argument." % (
               len(names), len(names) + len(failed), len(default)), "",
           "[Not carried](#not-carried) lists the %d left out, and why. "
           "[Accuracy](accuracy.md) has each one's measured error against "
           "upstream." % len(failed), ""]
    cats = {}
    for n in names:
        cats.setdefault(index[n]["category"] or "Uncategorized", []).append(n)
    order = sorted(c for c in cats if c != "Uncategorized")
    order += ["Uncategorized"] if "Uncategorized" in cats else []
    for cat in order:
        out += ["## %s" % cat, "",
                "| Plug-in | What it is | Parameters | |", "|---|---|---|---|"]
        for n in cats[cat]:
            knobs = ", ".join("`%s`" % p["py"] for p in index[n]["params"])
            tags = []
            if n in default:
                tags.append("**board**")
            if n in fast_ref:
                tags.append("[ref](#full-precision-on-boards)")
            out.append("| %s | %s | %s | %s |" % (
                n, _cell(sentence(n, index[n]["summary"])), knobs or "none",
                " ".join(tags)))
        out.append("")
    out += ["## Full precision on boards", "",
            "On a part whose FPU has no double, such as the ESP32-S3, each "
            "plug-in runs a single-precision copy of its loop, held to the "
            "same bar against upstream as the full-precision one. These %d, "
            "marked **ref** above, drift outside that bar in single "
            "precision, so a board runs upstream's arithmetic for them "
            "instead: the same sound, at a higher cost in time. The figure "
            "is how far the single-precision loop strayed, in int16 steps."
            % len(fast_ref), "",
            "| Plug-in | Single-precision error |", "|---|---|"]
    for n in fast_ref:
        out.append("| %s | %s |" % (n, policy[n].get("fast_error", "")))
    out += ["", "## Not carried", "", "| Plug-in | Why |", "|---|---|"]
    for n in sorted(failed):
        out.append("| %s | %s |" % (n, _cell(failed[n])))
    return "\n".join(out) + "\n"


def emit(root, index, policy, failed=None):
    """Writes every binding file. Returns the board default list."""
    names = sorted(index)
    for n in names:
        if len(index[n]["params"]) > MAX_PARAMS:
            raise ValueError("%s has more than %d parameters" % (n, MAX_PARAMS))
    default = board_default(index, policy)
    tpl = Path(__file__).parent / "templates"
    h, c = registry(names)
    files = {
        "src/airwindows/registry.h": h,
        "src/airwindows/registry.c": c,
        "src/airwindows/selection.txt": selection(index, default),
        "src/audioairwindows/module.c": mp_module(names),
        "src/audioairwindows/types.c": mp_types(names),
        "src/cpython/audioairwindows.py":
            (tpl / "audioairwindows.py").read_text().replace(
                "# @PLUGINS@\n", py_classes(index, names)),
        "audioairwindows.pyi":
            (tpl / "audioairwindows.pyi").read_text().replace(
                "# @PLUGINS@\n", pyi_classes(index, names)),
        "docs/reference/plugins.md":
            plugins_md(index, names, default, policy, failed or {}),
    }
    for rel, text in files.items():
        path = Path(root) / rel
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    return default
