"""Writes one plug-in's C kernel: src/airwindows/plugins/<Name>.c.

Each file holds the plug-in's state as a struct, its constructor and its
loop, twice: the reference (upstream's arithmetic, double where upstream
has double) and the fast variant (single precision, no divide or libm call
in the loop where it can be helped). A build compiles one or both
(AW_BUILD_REF, AW_BUILD_FAST in kernel.h) and the plug-in's descriptor
points at what it compiled.
"""

from pathlib import Path

from . import translate as tr
from .lex import code, join, lex, match, next_code, prev_code

TUNED_DIR = Path(__file__).parent / "tuned"

HEADER = """\
// GENERATED by tools/awgen from Airwindows {name} (plugins/LinuxVST/src/
// {name}/) at {commit}. Do not edit: change the generator and run
// `python -m tools.awgen`.
//
// {summary}
//
// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: Copyright (c) airwindows (Chris Johnson)
// SPDX-FileCopyrightText: Copyright (c) 2026 Brad Barnett
"""


def _ctype(ctype, fast, name=None, wide=(), phase=()):
    if fast and name in phase:
        return "uint64_t"
    if fast and name in wide:
        return "double"
    if fast and ctype in ("double", "long double"):
        return "float"
    if ctype == "VstInt32":
        return "int32_t"
    return ctype


def _struct(plugin, variant, statics, arith=None):
    fast = (arith or variant) == "fast"
    lines = ["typedef struct {",
             "    double aw_sample_rate;",
             "    uint32_t aw_rand;"]
    for m in plugin.members:
        dims = "".join("[%s]" % d for d in m.dims)
        ct = _ctype(m.ctype, fast, m.name, plugin.wide, plugin.phase)
        lines.append("    %s %s%s;" % (ct, m.name, dims))
    for ctype, name, _ in statics:
        lines.append("    %s %s;" % (_ctype(ctype, fast), name))
    lines.append("} aw_%s_%s_t;" % (plugin.name, variant))
    return "\n".join(lines)


def _member_io(plugin, body, variant, statics):
    """Loads of the members `body` uses, and stores of those it changes."""
    fast = variant == "fast"
    used = tr.identifiers(body)
    assigned = tr._assigned(body)
    loads, stores = [], []
    members = [(m.name, m.ctype, m.dims) for m in plugin.members] + \
        [(name, ctype, []) for ctype, name, _ in statics] + \
        [("aw_rand", "uint32_t", [])]
    for name, ctype, dims in members:
        if name not in used:
            continue
        ct = _ctype(ctype, fast, name, plugin.wide, plugin.phase)
        if dims:
            rest = "".join("[%s]" % d for d in dims[1:])
            if rest:
                loads.append("    %s (*%s)%s = aw_s->%s;" % (ct, name, rest,
                                                             name))
            else:
                loads.append("    %s *%s = aw_s->%s;" % (ct, name, name))
        else:
            loads.append("    %s %s = aw_s->%s;" % (ct, name, name))
            if name in assigned:
                stores.append("    aw_s->%s = %s;" % (name, name))
    return loads, stores


def _indent(text):
    return text


def translate_ctor(plugin, variant, seeds, issues):
    toks = list(plugin.ctor)
    toks, _ = tr.remove_statements(
        toks, lambda ts, i: ts[i].kind == "ident" and ts[i].text in
        tr.HOST_CALLS)

    # `fpdL = 1.0; while (fpdL < 16386) fpdL = rand()*UINT32_MAX;`
    out = []
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.kind == "ident" and t.text == "while":
            j = next_code(toks, i + 1)
            close = match(toks, j)
            head = [x.text for x in code(toks[j + 1:close])]
            if len(head) == 3 and head[1] == "<":
                s, e = tr.stmt_extent(toks, close + 1)
                body = [x.text for x in code(toks[close + 1:e + 1])]
                if "rand" in body:
                    name = head[0]
                    if name not in seeds:
                        seeds.append(name)
                    out.extend(tr._toks("%s = aw_seed(%d);" % (
                        name, seeds.index(name))))
                    i = e + 1
                    continue
        out.append(t)
        i += 1
    toks = out
    toks = _common(toks, variant, issues, plugin.fast_consts, plugin.wide)
    if variant == "fast":
        for name in plugin.phase:
            toks = tr.lower_phase_ctor(toks, name)
    return toks


# libm's constants are doubles; the fast variant writes them as float
# literals so they don't pull the arithmetic around them into double.
MATH_CONSTS = {k: tr._toks("(" + v + ")") for k, v in {
    "M_PI": "3.14159265358979323846", "M_PI_2": "1.57079632679489661923",
    "M_PI_4": "0.78539816339744830962", "M_E": "2.7182818284590452354",
    "M_SQRT2": "1.41421356237309504880",
    "M_SQRT1_2": "0.70710678118654752440",
    "M_LN2": "0.69314718055994530942", "M_LN10": "2.30258509299404568402",
    "M_1_PI": "0.31830988618379067154", "M_2_PI": "0.63661977236758134308",
}.items()}


def _common(toks, variant, issues, consts, wide=()):
    """What both variants change: C++ spellings and the host."""
    toks = tr.rewrite_get_sample_rate(toks)
    toks = tr.rewrite_casts(toks)
    toks = tr.rewrite_rand(toks)
    toks = tr.rewrite_calls(toks, {"abs": "aw_abs"})
    return toks


def _single(toks, issues, consts, wide=()):
    """The fast variant's per-sample arithmetic: single precision, our own
    sine and floor, small powers as multiplies."""
    toks = tr.rewrite_idents(toks, dict(MATH_CONSTS, **consts))
    toks = tr.to_single(toks, wide)
    toks = tr.rewrite_fast_math(toks, issues, wide)
    return toks


def _narrow_declarations(toks, names):
    """`double x;` becomes `float x;` for the names given."""
    if not names:
        return toks
    out = list(toks)
    for k, t in enumerate(out):
        if t.kind == "ident" and t.text in names:
            p = prev_code(out, k - 1)
            if p >= 0 and out[p].text in ("double", "float"):
                out[p] = tr.T("ident", "float")
                q = prev_code(out, p - 1)
                if q >= 0 and out[q].text == "long":
                    out[q] = tr.T("ws", "")
    return out


def translate_proc(plugin, variant, issues):
    toks = list(plugin.proc)
    names = tr.io_names(toks)
    # The host's pointers, and their increments.
    toks, _ = tr.remove_statements(
        toks, lambda ts, i: ts[i].kind == "ident" and ts[i].text in
        ("inputs", "outputs"))

    def increment(ts, i):
        if ts[i].text not in names:
            return False
        s, e = tr.stmt_extent(ts, i)
        words = [x.text for x in code(ts[s:e + 1])]
        return words in ([ts[i].text, "++", ";"],
                         ["*", ts[i].text, "++", ";"])
    toks, _ = tr.remove_statements(toks, increment)
    # The float output dither.
    toks, removed = tr.remove_statements(
        toks, lambda ts, i: ts[i].kind == "ident" and ts[i].text in
        ("expon", "frexpf", "frexp"))
    toks, statics, local_consts = tr.hoist_statics(toks)
    plugin_consts = getattr(plugin, "local_consts", None)
    if plugin_consts is None:
        plugin.local_consts = local_consts
    toks = tr.rewrite_io(toks, issues, names)
    toks = _common(toks, variant, issues, plugin.fast_consts, plugin.wide)
    if variant == "ref":
        ctypes = {m.name: m.ctype for m in plugin.members if not m.dims}
        ctypes.update(tr.declared_locals(toks))
        ctypes.update({name: ctype for ctype, name, _ in statics})
        toks = tr.rewrite_cxx_float_overloads(toks, ctypes)

    # Find the loop: while (--sampleFrames >= 0) { ... }
    loop_at = None
    for i, t in enumerate(toks):
        if t.text == "while":
            j = next_code(toks, i + 1)
            close = match(toks, j)
            if [x.text for x in code(toks[j + 1:close])] == \
                    ["--", "sampleFrames", ">=", "0"]:
                loop_at = (i, close)
                break
    if loop_at is None:
        raise tr.TranslateError("no `while (--sampleFrames >= 0)` loop")
    w, close = loop_at
    brace = next_code(toks, close + 1)
    if toks[brace].text != "{":
        raise tr.TranslateError("loop without braces")
    end = match(toks, brace)
    pre = toks[:w]
    loop = toks[brace + 1:end]
    post = toks[end + 1:]

    hoisted = []
    shadows = []
    phase_steps = []
    if variant == "fast":
        # Only the loop runs per sample. What comes before it runs once a
        # block, so it keeps upstream's double arithmetic (as cheap there as
        # it is accurate), and the loop reads float copies of its results.
        pre_locals = tr.declared_locals(pre)
        loop_locals = tr.declared_locals(loop)
        loop_assigned = tr._assigned(loop)
        used = tr.identifiers(loop)
        rename = {}
        # An array is a pointer to the loop; it keeps its declared type.
        arrays = {x.text for i, x in enumerate(pre[:-1]) if x.kind == "ident"
                  and pre[next_code(pre, i + 1)].text == "["}
        for name, ctype in pre_locals.items():
            if name in arrays:
                continue
            if ctype not in tr.FLOAT_TYPES or name in loop_locals or \
                    name not in used or name in plugin.wide:
                continue
            if name in loop_assigned:
                continue
            rename[name] = "aw_f_" + name
            shadows.append(name)
        # Pre-loop variables the loop works in become float.
        pre = _narrow_declarations(pre, {n for n, t in pre_locals.items()
                                         if n in loop_assigned and
                                         t in tr.FLOAT_TYPES and
                                         n not in plugin.wide})
        loop = tr.rewrite_idents(loop, {k: [tr.T("ident", v)]
                                        for k, v in rename.items()})
        loop = _single(loop, issues, plugin.fast_consts, plugin.wide)

        members = {m.name: m.ctype for m in plugin.members}
        for ctype, name, _ in statics:
            members[name] = ctype
        types = {k: ("float" if v in tr.FLOAT_TYPES and k not in plugin.wide
                     else v) for k, v in members.items()}
        for k, v in pre_locals.items():
            types[k] = "float" if v in tr.FLOAT_TYPES and \
                k not in plugin.wide else v
        for k in shadows:
            types["aw_f_" + k] = "float"
        for k, v in tr.declared_locals(loop).items():
            types.setdefault(k, v)
        types["aw_inL"] = types["aw_inR"] = "float"
        types["aw_outL"] = types["aw_outR"] = "float"
        types["aw_sample_rate"] = "double"
        outside = set(members) | set(pre_locals) | {"aw_sample_rate"} | {
            p.member for p in plugin.params} | {"aw_f_" + k for k in shadows}
        # Upper-case names are constants: enum values and macros.
        outside |= {x.text for x in loop if x.kind == "ident" and
                    x.text.isupper() and x.text not in members}
        outside |= set(_enum_names(plugin))
        loop = tr.rewrite_fast_divisions(loop, types, outside, hoisted)
        loop = tr.rewrite_int_sums(loop, types)
        loop = tr.rewrite_quiet_residue(loop)
        loop = tr.sink_into_branches(loop)
        loop = tr.rewrite_bounded_sines(loop)
        loop = tr.rewrite_mod_wrap(loop, types)
        for name in plugin.phase:
            loop, step = tr.lower_phase(loop, name)
            phase_steps.append((name, step))

    sfx = "fast" if variant == "fast" else "ref"
    head = tr._toks(
        "\n\t\tconst float aw_inL = AW_IN_L(aw_in);"
        "\n\t\tconst float aw_inR = AW_IN_R(aw_in, aw_channels);"
        "\n\t\tfloat aw_outL = 0.0f, aw_outR = 0.0f;")
    tail = tr._toks(
        "\t\tAW_OUT_%s(aw_out, aw_channels, aw_outL, aw_outR);\n"
        "\t\taw_in += aw_channels;\n\t\taw_out += aw_channels;\n\t"
        % sfx.upper())
    hoist = []
    for name in shadows:
        hoist += tr._toks("const float aw_f_%s = (float)%s;\n\t" % (name, name))
    for name, step in phase_steps:
        hoist += tr._toks("uint64_t aw_step_%s = AW_Q60_STEP(" % name) + \
            step + tr._toks(");\n\t")
    for name, expr in hoisted:
        hoist += tr._toks("const float %s = 1.0f / (" % name) + expr + \
            tr._toks(");\n\t")
    body = pre + hoist + toks[w:brace + 1] + head + \
        tr._toks("/* aw:loop */") + loop + tr._toks("/* aw:end */") + \
        tail + toks[end:end + 1] + post
    return body, statics


def _enum_names(plugin):
    out = []
    for text in plugin.class_enums + plugin.prelude:
        if text.startswith("enum"):
            for t in code(lex(text)):
                if t.kind == "ident" and t.text != "enum":
                    out.append(t.text)
    return out


_INT_TYPES = {"int", "unsigned", "long", "short", "char", "uint32_t",
              "int32_t", "uint16_t", "int16_t", "uint8_t", "int8_t",
              "VstInt32", "bool", "signed"}


def _split_top(toks, sep=","):
    out, cur, depth = [], [], 0
    for t in toks:
        if t.text in "([{":
            depth += 1
        elif t.text in ")]}":
            depth -= 1
        if depth == 0 and t.text == sep:
            out.append(cur)
            cur = []
        else:
            cur.append(t)
    out.append(cur)
    return out


def const_decl(text):
    """A file-scope or class constant as C, and for the fast variant a map
    of floating scalars to their values, which it writes inline in single
    precision rather than reading a double."""
    toks = [t for t in code(lex(text)) if t.text not in (
        "static", "const", "constexpr", ";")]
    k = 0
    while k < len(toks) and toks[k].text in tr.TYPE_WORDS:
        k += 1
    ctype = " ".join(t.text for t in toks[:k]) or "int"
    lines, fast = [], {}
    for decl in _split_top(toks[k:]):
        if not decl:
            continue
        name = decl[0].text
        words = [t.text for t in decl]
        eq = words.index("=") if "=" in words else len(words)
        dims = " ".join(words[1:eq])
        init = " ".join(words[eq + 1:]) if eq < len(words) else "0"
        is_int = all(w in _INT_TYPES for w in ctype.split())
        if is_int and not dims:
            lines.append("enum { %s = %s };" % (name, init))
        elif dims:
            lines.append("static const %s %s%s = %s;" % (
                ctype.replace("VstInt32", "int32_t"), name,
                dims.replace(" ", ""), init))
        else:
            lines.append("static const %s %s = %s;" % (ctype, name, init))
            fast[name] = tr._toks("((float)(%s))" % init)
    return lines, fast


def _prelude(plugin):
    lines = []
    for text in plugin.prelude:
        lines.append(text)
    plugin.fast_consts = {}
    for text in plugin.consts:
        c, f = const_decl(text)
        lines += c
        plugin.fast_consts.update(f)
    params = ", ".join("%s = %d" % (p.enum, p.index) for p in plugin.params)
    lines.append("enum { %s%skNumParameters = %d };" % (
        params, ", " if params else "", len(plugin.params)))
    for text in plugin.class_enums:
        lines.append(text)
    return lines


def emit(plugin, commit):
    """The plug-in's C file, and the issues translation found."""
    issues = []
    seeds = []
    plugin.local_consts = None
    prelude = _prelude(plugin)
    parts = [HEADER.format(name=plugin.name, commit=commit[:8],
                           summary=plugin.summary or plugin.name),
             '#include "airwindows/kernel_common.h"', "", None, ""]
    statics_seen = None
    for variant, guard in (("ref", "AW_BUILD_REF"), ("fast", "AW_BUILD_FAST")):
        # A plug-in whose single-precision loop can't meet the accuracy bar
        # (policy.json, "fast": false) runs upstream's arithmetic in its
        # fast slot too, so every build has it.
        arith = "ref" if variant == "fast" and plugin.fast_as_ref else variant
        body, statics = translate_proc(plugin, arith, issues)
        if variant == "ref":
            for text in plugin.local_consts or []:
                c, f = const_decl(text)
                prelude += c
                plugin.fast_consts.update(f)
        ctor = translate_ctor(plugin, arith, seeds, issues)
        statics_seen = statics
        init_tail = "".join("\t%s = %s;\n" % (name, init)
                            for _, name, init in statics)
        init_tail += "\taw_rand = AW_RAND_SEED;\n"
        ctor = ctor + tr._toks(init_tail)
        ld, st = _member_io(plugin, body, arith, statics)
        cld, cst = _member_io(plugin, ctor, arith, statics)
        cld = ["    aw_s->%s = %s;" % (m.name, m.init) for m in plugin.members
               if m.init is not None and not m.dims] + cld
        T = "aw_%s_%s_t" % (plugin.name, variant)
        if variant == "fast" and plugin.tuned:
            # policy.json, "tuned": a fast variant written by hand for the
            # targets plugin.h names in AW_TUNED. The translated one stays
            # for the rest.
            hand = (TUNED_DIR / (plugin.name + ".c")).read_text()
            parts.append("#if %s && AW_TUNED" % guard)
            parts.append(hand.rstrip("\n"))
            parts.append("#endif\n")
            guard += " && !AW_TUNED"
        parts.append("#if %s" % guard)
        parts.append(_struct(plugin, variant, statics, arith))
        parts.append("")
        parts.append(
            "static void aw_%s_init_%s(void *aw_state, double aw_rate) {\n"
            "    %s *aw_s = (%s *)aw_state;\n"
            "    memset(aw_s, 0, sizeof(*aw_s));\n"
            "    aw_s->aw_sample_rate = aw_rate;\n"
            "    aw_s->aw_rand = AW_RAND_SEED;\n"
            "    const double aw_sample_rate = aw_rate;\n"
            "    (void)aw_sample_rate;\n"
            "%s\n    {%s}\n%s\n}\n" % (
                plugin.name, variant, T, T, "\n".join(cld),
                join(ctor), "\n".join(cst)))
        parts.append(
            "static void aw_%s_process_%s(void *aw_state, int16_t *aw_out,\n"
            "    const int16_t *aw_in, int32_t sampleFrames, "
            "uint32_t aw_channels) {\n"
            "    %s *aw_s = (%s *)aw_state;\n"
            "    const double aw_sample_rate = aw_s->aw_sample_rate;\n"
            "    (void)aw_sample_rate;\n"
            "%s\n    {%s}\n%s\n}\n" % (
                plugin.name, variant, T, T, "\n".join(ld),
                join(body), "\n".join(st)))
        offs = ", ".join("offsetof(%s, %s)" % (T, p.member)
                         for p in plugin.params) or "0"
        parts.append("static const uint32_t aw_%s_offsets_%s[] = {%s};" % (
            plugin.name, variant, offs))
        parts.append("#endif\n")
    parts[3] = "\n".join(prelude)
    plugin.statics = statics_seen
    plugin.seeds = seeds
    # Parameters and the descriptor.
    rows = "\n".join('    {"%s", "%s", %r},' % (
        p.py, p.name.replace('"', '\\"'), float(p.default))
        for p in plugin.params) or '    {"", "", 0.0f},'
    parts.append("static const aw_param_t aw_%s_params[] = {\n%s\n};\n" % (
        plugin.name, rows.replace(".0},", ".0f},")))
    parts.append(DESCRIPTOR.format(n=plugin.name, count=len(plugin.params)))
    return "\n".join(parts), issues


DESCRIPTOR = """\
const aw_plugin_t aw_plugin_{n} = {{
    .name = "{n}",
    .param_count = {count},
    .params = aw_{n}_params,
#if AW_BUILD_REF
    .ref = {{sizeof(aw_{n}_ref_t), aw_{n}_init_ref, aw_{n}_process_ref,
        aw_{n}_offsets_ref}},
#endif
#if AW_BUILD_FAST
    .fast = {{sizeof(aw_{n}_fast_t), aw_{n}_init_fast, aw_{n}_process_fast,
        aw_{n}_offsets_fast}},
#endif
}};
"""
